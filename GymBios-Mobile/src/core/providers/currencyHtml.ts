/**
 * Currency prefix for HTML output (PDF receipts/reports via expo-print). HTML can
 * draw the real Dirham sign inline, so AED gets the SVG mark instead of "AED ".
 */
export function currencyHtmlPrefix(code: CurrencyCode): string {
  if (code === 'AED') return DIRHAM_SVG;
  const def = CURRENCIES.find((c) => c.code === code) ?? CURRENCIES[0];
  return def.textPrefix;
}

/** "[symbol]1,250.00" as an HTML fragment. `amountText` must already be formatted/escaped. */
export function currencyHtml(code: CurrencyCode, amountText: string): string {
  return `<span style="white-space:nowrap">${currencyHtmlPrefix(code)}${amountText}</span>`;
}
