import React from 'react';
import { Card, CardContent, CardDescription, CardHeader, CardTitle } from "../ui/card";
import { Button } from "../ui/button";
import { Badge } from "../ui/badge";
import { Progress } from "../ui/progress";
import { Tabs, TabsContent, TabsList, TabsTrigger } from "../ui/tabs";
import { Table, TableBody, TableCell, TableHead, TableHeader, TableRow } from "../ui/table";
import { Dialog, DialogContent, DialogDescription, DialogHeader, DialogTitle } from "../ui/dialog";
import { Separator } from "../ui/separator";
import { Input } from "../ui/input";
import { Label } from "../ui/label";
import { Select, SelectContent, SelectItem, SelectTrigger, SelectValue } from "../ui/select";
import { Checkbox } from "../ui/checkbox";
import { Textarea } from "../ui/textarea";
import { LineChart, Line, BarChart, Bar, XAxis, YAxis, CartesianGrid, Tooltip, ResponsiveContainer, Legend } from 'recharts';
import {
  Activity,
  FileText,
  Download,
  Eye,
  Calendar,
  Clock,
  Filter,
  RefreshCw,
  Settings,
  CheckCircle,
  AlertTriangle,
  Plus,
  Trash2,
  Edit,
  Copy,
  Send,
  Mail,
  Printer,
  Share2,
  Archive,
  Folder,
  FolderOpen,
  FileSpreadsheet,
  FilePlus,
  FileCheck,
  FileX,
  TrendingUp,
  Users,
  DollarSign,
  Target,
  Package,
  ShoppingCart,
  Wrench,
  UserCheck,
  BarChart3,
  PieChart,
  Zap,
  Star
} from 'lucide-react';
import type { BiosActivityLogEntry } from '../../utils/supabase/bios-service';
import { type BiosLiveData, useBiosInsights, InsightsStatus, BiosScheduleTable, biosSchedules } from './bios-live';
import { biosInsightsService } from '../../utils/supabase/bios-insights-service';

interface OperationalReportsDialogProps {
  open: boolean;
  onOpenChange: (open: boolean) => void;
  defaultTab?: string;
  recentReports: Array<{
    report: string;
    type: string;
    generated: string;
    downloads: number;
    status: string;
  }>;
  formatCurrency: (amount: number) => string;
  getCurrentPeriod: () => string;
  live: BiosLiveData;
  /** Real BiOS activity log (generated reports and data exports). */
  activityLog: BiosActivityLogEntry[];
  reportsThisMonth: number;
  exportsThisWeek: number;
  formatRelativeTime: (iso?: string | null) => string;
  onRefreshLog: () => void;
}

export function OperationalReportsDialog({
  open,
  onOpenChange,
  defaultTab = 'reports',
  recentReports,
  formatCurrency,
  getCurrentPeriod,
  live,
  activityLog,
  reportsThisMonth,
  exportsThisWeek,
  formatRelativeTime,
  onRefreshLog
}: OperationalReportsDialogProps) {
  const [selectedReportType, setSelectedReportType] = React.useState('all');
  const [selectedPeriod, setSelectedPeriod] = React.useState('monthly');

  // Report Library — every report and export generated from BiOS.
  const reportLibrary = activityLog.map((entry, index) => ({
    id: index + 1,
    kind: entry.type,
    name: entry.title,
    type: entry.type === 'REPORT' ? 'Operational' : 'Analytics',
    description: `${entry.type === 'REPORT' ? 'KPI summary report' : 'Full data export'} generated by ${entry.generated_by || 'Unknown'}`,
    generated: entry.created_at ?? '',
    frequency: 'On demand',
    size: '—',
    pages: entry.row_count ?? 0,
    downloads: '—',
    status: 'Available',
    lastRun: formatRelativeTime(entry.created_at),
    nextScheduled: '—',
    format: entry.format,
    recipients: [] as string[]
  }));
  const regenerate = (kind: string) => (kind === 'REPORT' ? live.onExportReport() : live.onExportData());

  // Report activity by month (last 6 months), from the BiOS activity log.
  const { data: operations, loading: operationsLoading, error: operationsError } =
    useBiosInsights(() => biosInsightsService.getOperations(), open, live.branchKey);
  const generationStats = (operations?.report_activity ?? []).map((m) => {
    const [year, month] = m.period.split('-').map(Number);
    return {
      month: new Date(year, month - 1, 1).toLocaleDateString('en-GB', { month: 'short' }),
      reports: m.reports,
      exports: m.exports
    };
  });
  const totalReports6m = generationStats.reduce((sum, m) => sum + m.reports, 0);
  const totalExports6m = generationStats.reduce((sum, m) => sum + m.exports, 0);
  const reportCategories = [
    { category: 'KPI summary reports', count: totalReports6m, color: '#10b981' },
    { category: 'Full data exports', count: totalExports6m, color: '#3b82f6' }
  ].map((c) => ({ ...c, percentage: totalReports6m + totalExports6m > 0 ? Number(((c.count / (totalReports6m + totalExports6m)) * 100).toFixed(1)) : 0 }));
  const activeSchedules = biosSchedules(live.settings).filter((schedule) => schedule.enabled).length;

  // The reports BiOS can produce right now (both CSV).
  const availableReports = [
    { name: 'KPI Summary Report', description: 'Headline revenue, member, retention and target figures for the current view', run: live.onExportReport },
    { name: 'Full Data Export', description: 'Every BiOS series — revenue, members, sources, expenses — as one CSV', run: live.onExportData }
  ];

  const getStatusColor = (status: string) => {
    switch (status) {
      case 'Available':
        return 'bg-green-100 text-green-800';
      case 'Generating':
        return 'bg-blue-100 text-blue-800';
      case 'Failed':
        return 'bg-red-100 text-red-800';
      case 'Scheduled':
        return 'bg-yellow-100 text-yellow-800';
      default:
        return 'bg-gray-100 text-gray-800';
    }
  };

  const getTypeIcon = (type: string) => {
    switch (type) {
      case 'Financial':
        return <DollarSign className="h-4 w-4 text-green-600" />;
      case 'Analytics':
        return <BarChart3 className="h-4 w-4 text-purple-600" />;
      case 'Operational':
        return <Activity className="h-4 w-4 text-blue-600" />;
      case 'HR':
        return <Users className="h-4 w-4 text-orange-600" />;
      case 'Retail':
        return <ShoppingCart className="h-4 w-4 text-red-600" />;
      default:
        return <FileText className="h-4 w-4 text-gray-600" />;
    }
  };

  return (
    <Dialog open={open} onOpenChange={onOpenChange}>
      <DialogContent data-bios-ui="" className="max-w-7xl sm:max-w-7xl max-h-[90vh] overflow-y-auto">
        <DialogHeader>
          <DialogTitle className="flex items-center space-x-2">
            <FileText className="h-6 w-6 text-[#2B7A78]" />
            <span>Operational Reports - {getCurrentPeriod()}</span>
          </DialogTitle>
          <DialogDescription>
            Generate, schedule, and manage comprehensive operational reports
          </DialogDescription>
        </DialogHeader>

        <Tabs defaultValue={defaultTab} className="w-full">
          <TabsList className="grid w-full grid-cols-4">
            <TabsTrigger value="reports">All Reports</TabsTrigger>
            <TabsTrigger value="generate">Generate</TabsTrigger>
            <TabsTrigger value="scheduled">Scheduled</TabsTrigger>
            <TabsTrigger value="analytics">Analytics</TabsTrigger>
          </TabsList>

          {/* All Reports Tab */}
          <TabsContent value="reports" className="space-y-4">
            <div className="flex items-center justify-between">
              <div className="flex items-center space-x-3">
                <Folder className="h-5 w-5 text-[#2B7A78]" />
                <div>
                  <h3 className="font-semibold">Report Library</h3>
                  <p className="text-sm text-muted-foreground">{reportLibrary.length} reports available</p>
                </div>
              </div>
              <div className="flex items-center space-x-2">
                <Select value={selectedReportType} onValueChange={setSelectedReportType}>
                  <SelectTrigger className="w-40">
                    <SelectValue />
                  </SelectTrigger>
                  <SelectContent>
                    <SelectItem value="all">All Types</SelectItem>
                    <SelectItem value="financial">Financial</SelectItem>
                    <SelectItem value="operational">Operational</SelectItem>
                    <SelectItem value="analytics">Analytics</SelectItem>
                    <SelectItem value="hr">HR</SelectItem>
                    <SelectItem value="retail">Retail</SelectItem>
                  </SelectContent>
                </Select>
                <Button size="sm" variant="outline">
                  <Filter className="h-4 w-4 mr-2" />
                  Filter
                </Button>
                <Button size="sm" variant="outline" onClick={onRefreshLog}>
                  <RefreshCw className="h-4 w-4 mr-2" />
                  Refresh
                </Button>
              </div>
            </div>

            <Separator />

            <div className="grid grid-cols-1 gap-4">
              {reportLibrary.length === 0 && (
                <p className="text-sm text-muted-foreground">No reports generated yet — use Generate or Quick Generate to create one.</p>
              )}
              {reportLibrary.filter((r) => selectedReportType === 'all' || r.type.toLowerCase() === selectedReportType).map((report) => (
                <Card key={report.id}>
                  <CardHeader>
                    <div className="flex items-start justify-between">
                      <div className="flex items-start space-x-3 flex-1">
                        {getTypeIcon(report.type)}
                        <div className="flex-1">
                          <div className="flex items-center space-x-2 mb-1">
                            <CardTitle className="text-base">{report.name}</CardTitle>
                            <Badge className={getStatusColor(report.status)}>
                              {report.status}
                            </Badge>
                            <Badge variant="outline">{report.type}</Badge>
                          </div>
                          <CardDescription className="mt-1">{report.description}</CardDescription>
                        </div>
                      </div>
                    </div>
                  </CardHeader>
                  <CardContent>
                    <div className="grid grid-cols-2 md:grid-cols-6 gap-4 mb-4">
                      <div>
                        <p className="text-xs text-muted-foreground mb-1">Generated</p>
                        <p className="text-sm font-medium">{report.lastRun}</p>
                      </div>
                      <div>
                        <p className="text-xs text-muted-foreground mb-1">Frequency</p>
                        <p className="text-sm">{report.frequency}</p>
                      </div>
                      <div>
                        <p className="text-xs text-muted-foreground mb-1">Size</p>
                        <p className="text-sm">{report.size}</p>
                      </div>
                      <div>
                        <p className="text-xs text-muted-foreground mb-1">Rows</p>
                        <p className="text-sm">{report.pages}</p>
                      </div>
                      <div>
                        <p className="text-xs text-muted-foreground mb-1">Downloads</p>
                        <p className="text-sm font-medium">{report.downloads}</p>
                      </div>
                      <div>
                        <p className="text-xs text-muted-foreground mb-1">Format</p>
                        <Badge variant="outline">{report.format}</Badge>
                      </div>
                    </div>
                    <div className="flex space-x-2">
                      <Button size="sm" className="bg-[#2B7A78] hover:bg-[#236663]" onClick={() => regenerate(report.kind)} title="Download a fresh copy with today's figures">
                        <Download className="h-4 w-4 mr-2" />
                        Download
                      </Button>
                      <Button size="sm" variant="outline">
                        <Eye className="h-4 w-4 mr-2" />
                        View
                      </Button>
                      <Button size="sm" variant="outline">
                        <Send className="h-4 w-4 mr-2" />
                        Send
                      </Button>
                      <Button size="sm" variant="outline">
                        <Copy className="h-4 w-4 mr-2" />
                        Duplicate
                      </Button>
                      <Button size="sm" variant="outline">
                        <Archive className="h-4 w-4 mr-2" />
                        Archive
                      </Button>
                    </div>
                  </CardContent>
                </Card>
              ))}
            </div>
          </TabsContent>

          {/* Generate Tab */}
          <TabsContent value="generate" className="space-y-4">
            <div className="grid grid-cols-1 md:grid-cols-2 gap-4">
              {availableReports.map((report) => (
                <Card key={report.name}>
                  <CardHeader>
                    <CardTitle className="text-base">{report.name}</CardTitle>
                    <CardDescription>{report.description}</CardDescription>
                  </CardHeader>
                  <CardContent>
                    <Button className="w-full bg-[#2B7A78] hover:bg-[#236663]" onClick={report.run}>
                      <Download className="h-4 w-4 mr-2" />
                      Download CSV
                    </Button>
                  </CardContent>
                </Card>
              ))}
            </div>
            <p className="text-xs text-muted-foreground">Each download is logged under All Reports.</p>
          </TabsContent>

          {/* Scheduled Tab */}
          <TabsContent value="scheduled" className="space-y-4">
            <div>
              <h3 className="font-semibold">Scheduled Reports</h3>
              <p className="text-sm text-muted-foreground">{activeSchedules} switched on for this branch</p>
            </div>
            <Card>
              <CardContent className="pt-6">
                <BiosScheduleTable settings={live.settings} onConfigure={live.onConfigure} />
              </CardContent>
            </Card>
          </TabsContent>

          {/* Analytics Tab */}
          <TabsContent value="analytics" className="space-y-4">
            <div className="grid grid-cols-1 md:grid-cols-3 gap-4">
              <Card>
                <CardContent className="p-6">
                  <div className="flex items-center justify-between">
                    <div>
                      <p className="text-sm text-muted-foreground">Reports Generated</p>
                      <p className="text-2xl font-bold">{reportsThisMonth}</p>
                      <p className="text-xs text-green-600 mt-1">This month</p>
                    </div>
                    <FileCheck className="h-10 w-10 text-green-600 opacity-20" />
                  </div>
                </CardContent>
              </Card>

              <Card>
                <CardContent className="p-6">
                  <div className="flex items-center justify-between">
                    <div>
                      <p className="text-sm text-muted-foreground">Data Exports</p>
                      <p className="text-2xl font-bold">{exportsThisWeek}</p>
                      <p className="text-xs text-blue-600 mt-1">Last 7 days</p>
                    </div>
                    <Download className="h-10 w-10 text-blue-600 opacity-20" />
                  </div>
                </CardContent>
              </Card>

              <Card>
                <CardContent className="p-6">
                  <div className="flex items-center justify-between">
                    <div>
                      <p className="text-sm text-muted-foreground">Schedules On</p>
                      <p className="text-2xl font-bold">{activeSchedules}</p>
                      <p className="text-xs text-purple-600 mt-1">Reports and alerts</p>
                    </div>
                    <Calendar className="h-10 w-10 text-purple-600 opacity-20" />
                  </div>
                </CardContent>
              </Card>
            </div>

            <Card>
              <CardHeader>
                <CardTitle className="text-base">Report Generation Trends</CardTitle>
                <CardDescription>Reports and exports generated from BiOS, last 6 months</CardDescription>
              </CardHeader>
              <CardContent>
                <InsightsStatus loading={operationsLoading} error={operationsError} />
                <ResponsiveContainer width="100%" height={300}>
                  <LineChart data={generationStats}>
                    <CartesianGrid strokeDasharray="3 3" />
                    <XAxis dataKey="month" />
                    <YAxis />
                    <Tooltip />
                    <Legend />
                    <Line type="monotone" dataKey="reports" stroke="#2B7A78" strokeWidth={2} name="Reports Generated" />
                    <Line type="monotone" dataKey="exports" stroke="#3b82f6" strokeWidth={2} name="Data Exports" />
                  </LineChart>
                </ResponsiveContainer>
              </CardContent>
            </Card>

            <Card>
              <CardHeader>
                <CardTitle className="text-base">Reports by Type</CardTitle>
                <CardDescription>Last 6 months</CardDescription>
              </CardHeader>
              <CardContent>
                <div className="space-y-3">
                  {reportCategories.map((cat, index) => (
                    <div key={index}>
                      <div className="flex justify-between items-center mb-1">
                        <div className="flex items-center space-x-2">
                          <div className="w-3 h-3 rounded-full" style={{ backgroundColor: cat.color }} />
                          <span className="text-sm font-medium">{cat.category}</span>
                        </div>
                        <div className="text-right">
                          <span className="text-sm font-medium">{cat.count} reports</span>
                          <span className="text-xs text-muted-foreground ml-2">({cat.percentage}%)</span>
                        </div>
                      </div>
                      <Progress value={cat.percentage} className="h-2" />
                    </div>
                  ))}
                </div>
              </CardContent>
            </Card>
          </TabsContent>

        </Tabs>

        <div className="flex justify-end space-x-2 pt-4 border-t">
          <Button variant="outline" onClick={() => onOpenChange(false)}>
            Close
          </Button>
          <Button className="bg-[#2B7A78] hover:bg-[#236663]" onClick={live.onExportReport}>
            <Zap className="h-4 w-4 mr-2" />
            Generate Report
          </Button>
          <Button className="bg-[#E63946] hover:bg-[#d32f3f]" onClick={live.onExportData}>
            <Download className="h-4 w-4 mr-2" />
            Download All
          </Button>
        </div>
      </DialogContent>
    </Dialog>
  );
}
