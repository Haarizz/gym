-- A gym asks to link one of its member records to a GymBios account that already
-- exists (the person signed up themselves, or at another gym). Nothing is linked
-- until the account owner accepts in their own app. Lives here, not in a tenant
-- database, because the person reads their pending requests without a gym selected.
CREATE TABLE IF NOT EXISTS account_link_requests (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    global_user_id  BIGINT       NOT NULL,
    tenant_slug     VARCHAR(100) NOT NULL,
    -- Tenant-DB members.id; not a FK since it lives in another database.
    member_id       BIGINT       NOT NULL,
    gym_name        VARCHAR(255),
    member_name     VARCHAR(255),
    requested_by    VARCHAR(255),
    -- PENDING | ACCEPTED | DECLINED | CANCELLED
    status          VARCHAR(20)  NOT NULL DEFAULT 'PENDING',
    decided_at      TIMESTAMP,
    expires_at      TIMESTAMP    NOT NULL,
    created_at      TIMESTAMP    NOT NULL DEFAULT NOW(),
    updated_at      TIMESTAMP,
    created_by      VARCHAR(255),
    updated_by      VARCHAR(255)
);
CREATE INDEX IF NOT EXISTS idx_account_link_requests_user ON account_link_requests (global_user_id, status);
CREATE INDEX IF NOT EXISTS idx_account_link_requests_member ON account_link_requests (tenant_slug, member_id, status);

-- Short-lived codes emailed to a GymBios account: verifying its email address, and
-- resetting a forgotten password. Hashed at rest like registration OTPs.
CREATE TABLE IF NOT EXISTS account_codes (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    global_user_id  BIGINT       NOT NULL,
    -- EMAIL_VERIFY | PASSWORD_RESET
    purpose         VARCHAR(20)  NOT NULL,
    email           VARCHAR(255) NOT NULL,
    code_hash       VARCHAR(255) NOT NULL,
    attempt_count   INT          NOT NULL DEFAULT 0,
    expires_at      TIMESTAMP    NOT NULL,
    consumed_at     TIMESTAMP,
    created_at      TIMESTAMP    NOT NULL DEFAULT NOW(),
    updated_at      TIMESTAMP,
    created_by      VARCHAR(255),
    updated_by      VARCHAR(255)
);
CREATE INDEX IF NOT EXISTS idx_account_codes_user ON account_codes (global_user_id, purpose, created_at);
