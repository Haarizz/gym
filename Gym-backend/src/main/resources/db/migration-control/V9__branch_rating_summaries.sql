-- ============================================================
-- V9: Branch rating summaries
-- Per-branch roll-up of each gym's member reviews (tenant-DB reviews table),
-- so the platform admin's Ratings list can show every gym without opening
-- every tenant database. Refreshed whenever a review is saved, and fully
-- recomputed on startup (BranchRatingSummaryBackfillRunner). Individual
-- reviews are still read live from the gym's own database.
-- ============================================================

CREATE TABLE IF NOT EXISTS branch_rating_summaries (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_slug     VARCHAR(100) NOT NULL,
    -- Tenant-DB branches.id; not a FK since it lives in another database.
    branch_id       BIGINT       NOT NULL,
    branch_name     VARCHAR(255),
    rating_count    BIGINT       NOT NULL DEFAULT 0,
    rating_sum      BIGINT       NOT NULL DEFAULT 0,
    star1           BIGINT       NOT NULL DEFAULT 0,
    star2           BIGINT       NOT NULL DEFAULT 0,
    star3           BIGINT       NOT NULL DEFAULT 0,
    star4           BIGINT       NOT NULL DEFAULT 0,
    star5           BIGINT       NOT NULL DEFAULT 0,
    last_review_at  TIMESTAMP,
    created_at      TIMESTAMP    NOT NULL DEFAULT NOW(),
    updated_at      TIMESTAMP,
    created_by      VARCHAR(255),
    updated_by      VARCHAR(255),
    UNIQUE (tenant_slug, branch_id)
);
