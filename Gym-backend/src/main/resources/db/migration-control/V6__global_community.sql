-- ── Moderation ──────────────────────────────────────────────────────────────

-- Two independent hide scopes for comments (C5). A comment is hidden while any
-- row exists; each scope can only remove its own row.
CREATE TABLE IF NOT EXISTS community_comment_hides (
    comment_id           BIGINT       NOT NULL REFERENCES global_community_comments (id),
    scope                VARCHAR(20)  NOT NULL,
    scope_tenant_slug    VARCHAR(100),
    hidden_by_author_id  BIGINT       NOT NULL REFERENCES community_authors (id),
    reason               VARCHAR(500),
    created_at           TIMESTAMP    NOT NULL DEFAULT NOW(),
    PRIMARY KEY (comment_id, scope),
    CONSTRAINT ck_cch_scope CHECK (scope IN ('AUTHOR_GYM', 'POST_OWNER_GYM', 'PLATFORM')),
    CONSTRAINT ck_cch_scope_slug CHECK ((scope = 'PLATFORM') = (scope_tenant_slug IS NULL))
);

CREATE TABLE IF NOT EXISTS community_moderation_actions (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    target_type       VARCHAR(16)  NOT NULL,
    target_id         BIGINT       NOT NULL,
    action            VARCHAR(24)  NOT NULL,
    scope             VARCHAR(20)  NOT NULL,
    actor_author_id   BIGINT       NOT NULL REFERENCES community_authors (id),
    actor_tenant_slug VARCHAR(100),
    reason            VARCHAR(500),
    created_at        TIMESTAMP    NOT NULL DEFAULT NOW(),
    CONSTRAINT ck_cma_target CHECK (target_type IN ('POST', 'COMMENT', 'REPORT')),
    CONSTRAINT ck_cma_action CHECK (action IN ('HIDE', 'RESTORE', 'ARCHIVE', 'UNARCHIVE', 'DELETE',
                                               'RESOLVE_REPORT', 'DISMISS_REPORT', 'ESCALATE_REPORT')),
    CONSTRAINT ck_cma_scope CHECK (scope IN ('AUTHOR', 'AUTHOR_GYM', 'POST_OWNER_GYM', 'PLATFORM', 'SYSTEM'))
);

CREATE INDEX IF NOT EXISTS ix_cma_target ON community_moderation_actions (target_type, target_id, created_at);

