-- Global Community store (control plane).
--
-- Visibility is global; moderation authority follows the author's gym
-- (author_tenant_slug). Identity is modelled explicitly in community_authors so
-- global user IDs and tenant-local user IDs are never compared directly.
--
-- Idempotent: every object uses IF NOT EXISTS / CREATE OR REPLACE / DROP ... IF
-- EXISTS, so re-running against a partially applied schema is safe. Nothing here
-- is read by the application until the rollout flags enable it.
--
-- Legacy rows carry their origin (legacy_source = 'primary' | 'tenant:<slug>',
-- legacy_id) directly, with a UNIQUE constraint, so "exactly one global row per
-- legacy row" is enforced by the database rather than by application code.

-- ── Identity ────────────────────────────────────────────────────────────────

CREATE TABLE IF NOT EXISTS community_authors (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    kind              VARCHAR(16)  NOT NULL,
    global_user_id    BIGINT,
    tenant_slug       VARCHAR(100),
    tenant_user_id    BIGINT,
    platform_user_id  BIGINT,
    display_name      VARCHAR(120) NOT NULL,
    avatar_url        TEXT,
    primary_role      VARCHAR(64),
    status            VARCHAR(16)  NOT NULL DEFAULT 'ACTIVE',
    created_at        TIMESTAMP    NOT NULL DEFAULT NOW(),
    updated_at        TIMESTAMP,
    CONSTRAINT ck_community_authors_kind CHECK (kind IN ('GLOBAL', 'TENANT', 'PLATFORM')),
    CONSTRAINT ck_community_authors_status CHECK (status IN ('ACTIVE', 'SUSPENDED')),
    CONSTRAINT ck_community_authors_identity CHECK (
        (kind = 'GLOBAL'   AND global_user_id IS NOT NULL AND tenant_slug IS NULL AND tenant_user_id IS NULL AND platform_user_id IS NULL)
     OR (kind = 'TENANT'   AND global_user_id IS NULL AND tenant_slug IS NOT NULL AND tenant_user_id IS NOT NULL AND platform_user_id IS NULL)
     OR (kind = 'PLATFORM' AND global_user_id IS NULL AND tenant_slug IS NULL AND tenant_user_id IS NULL AND platform_user_id IS NOT NULL)
    ),
    CONSTRAINT ck_community_authors_slug CHECK (tenant_slug IS NULL OR (tenant_slug <> '' AND tenant_slug !~ '\s'))
);

CREATE UNIQUE INDEX IF NOT EXISTS ux_community_authors_global
    ON community_authors (global_user_id) WHERE kind = 'GLOBAL';
CREATE UNIQUE INDEX IF NOT EXISTS ux_community_authors_tenant
    ON community_authors (tenant_slug, tenant_user_id) WHERE kind = 'TENANT';
CREATE UNIQUE INDEX IF NOT EXISTS ux_community_authors_platform
    ON community_authors (platform_user_id) WHERE kind = 'PLATFORM';

-- ── Posts ───────────────────────────────────────────────────────────────────

CREATE TABLE IF NOT EXISTS global_community_posts (
    id                   BIGINT GENERATED BY DEFAULT AS IDENTITY (START WITH 1000000000) PRIMARY KEY,
    author_id            BIGINT       NOT NULL REFERENCES community_authors (id),
    author_tenant_slug   VARCHAR(100) NOT NULL,
    author_branch_id     BIGINT,
    author_member_id     BIGINT,
    author_gym_name      VARCHAR(255),
    author_branch_name   VARCHAR(255),
    topic                VARCHAR(140) NOT NULL,
    content              TEXT         NOT NULL,
    type                 VARCHAR(32)  NOT NULL,
    visibility           VARCHAR(16)  NOT NULL DEFAULT 'PUBLIC',
    status               VARCHAR(16)  NOT NULL DEFAULT 'ACTIVE',
    origin               VARCHAR(16)  NOT NULL,
    like_count           INTEGER      NOT NULL DEFAULT 0,
    comment_count        INTEGER      NOT NULL DEFAULT 0,
    hidden_at            TIMESTAMP,
    hidden_by_author_id  BIGINT REFERENCES community_authors (id),
    hidden_reason        VARCHAR(500),
    archived_at          TIMESTAMP,
    deleted_at           TIMESTAMP,
    legacy_source        VARCHAR(120),
    legacy_id            BIGINT,
    legacy_fingerprint   VARCHAR(64),
    created_at           TIMESTAMP    NOT NULL DEFAULT NOW(),
    updated_at           TIMESTAMP,
    CONSTRAINT ck_gcp_visibility CHECK (visibility IN ('PUBLIC', 'GYM')),
    CONSTRAINT ck_gcp_status CHECK (status IN ('ACTIVE', 'ARCHIVED', 'HIDDEN', 'DELETED')),
    CONSTRAINT ck_gcp_origin CHECK (origin IN ('LEGACY', 'GLOBAL')),
    CONSTRAINT ck_gcp_counters CHECK (like_count >= 0 AND comment_count >= 0),
    CONSTRAINT ck_gcp_slug CHECK (author_tenant_slug <> '' AND author_tenant_slug !~ '\s'),
    CONSTRAINT ck_gcp_legacy CHECK (
        (origin = 'LEGACY' AND legacy_source IS NOT NULL AND legacy_id IS NOT NULL AND legacy_fingerprint IS NOT NULL)
     OR (origin = 'GLOBAL' AND legacy_source IS NULL AND legacy_id IS NULL AND legacy_fingerprint IS NULL)
    ),
    -- New content obeys the approved limits; migrated legacy content is kept verbatim.
    CONSTRAINT ck_gcp_content_limit CHECK (origin = 'LEGACY' OR char_length(content) <= 1000),
    CONSTRAINT ck_gcp_hidden_state CHECK (status <> 'HIDDEN' OR (hidden_at IS NOT NULL AND hidden_by_author_id IS NOT NULL)),
    CONSTRAINT ck_gcp_deleted_state CHECK (status <> 'DELETED' OR deleted_at IS NOT NULL),
    CONSTRAINT ux_gcp_legacy UNIQUE (legacy_source, legacy_id)
);

CREATE INDEX IF NOT EXISTS ix_gcp_public_feed
    ON global_community_posts (created_at DESC, id DESC) WHERE status = 'ACTIVE' AND visibility = 'PUBLIC';
CREATE INDEX IF NOT EXISTS ix_gcp_gym_feed
    ON global_community_posts (author_tenant_slug, created_at DESC, id DESC);
CREATE INDEX IF NOT EXISTS ix_gcp_author
    ON global_community_posts (author_id, created_at DESC, id DESC);

CREATE TABLE IF NOT EXISTS global_community_post_images (
    post_id        BIGINT      PRIMARY KEY REFERENCES global_community_posts (id),
    origin         VARCHAR(16) NOT NULL,
    content_type   VARCHAR(64) NOT NULL,
    data           BYTEA       NOT NULL,
    byte_size      INTEGER     NOT NULL,
    width          INTEGER,
    height         INTEGER,
    aspect_ratio   VARCHAR(8),
    crop_position  INTEGER,
    crop_zoom      INTEGER,
    sha256         CHAR(64)    NOT NULL,
    created_at     TIMESTAMP   NOT NULL DEFAULT NOW(),
    CONSTRAINT ck_gcpi_origin CHECK (origin IN ('LEGACY', 'GLOBAL')),
    CONSTRAINT ck_gcpi_type CHECK (content_type LIKE 'image/%'),
    CONSTRAINT ck_gcpi_size CHECK (byte_size > 0 AND byte_size = octet_length(data)),
    CONSTRAINT ck_gcpi_dimensions CHECK ((width IS NULL OR width > 0) AND (height IS NULL OR height > 0)),
    -- C9 limits for new uploads: one JPEG/PNG, <= 1.5 MB decoded, <= 2048x2048.
    CONSTRAINT ck_gcpi_new_upload_limits CHECK (
        origin = 'LEGACY'
     OR (content_type IN ('image/jpeg', 'image/png') AND byte_size <= 1572864
         AND width IS NOT NULL AND height IS NOT NULL AND width <= 2048 AND height <= 2048)
    )
);

