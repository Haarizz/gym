    CONSTRAINT ck_gcc_deleted_state CHECK (status <> 'DELETED' OR deleted_at IS NOT NULL),
    CONSTRAINT ux_gcc_legacy UNIQUE (legacy_source, legacy_id)
);

CREATE INDEX IF NOT EXISTS ix_gcc_post ON global_community_comments (post_id, created_at, id);
CREATE INDEX IF NOT EXISTS ix_gcc_author_gym ON global_community_comments (author_tenant_slug, created_at DESC);

