CREATE TABLE IF NOT EXISTS community_rollout_state (
    id                              SMALLINT     PRIMARY KEY DEFAULT 1,
    authority                       VARCHAR(8)   NOT NULL DEFAULT 'LEGACY',
    write_mode                      VARCHAR(16)  NOT NULL DEFAULT 'OPEN',
    op_post                         BOOLEAN      NOT NULL DEFAULT FALSE,
    op_comment                      BOOLEAN      NOT NULL DEFAULT FALSE,
    op_like                         BOOLEAN      NOT NULL DEFAULT FALSE,
    op_report                       BOOLEAN      NOT NULL DEFAULT FALSE,
    global_reads                    BOOLEAN      NOT NULL DEFAULT FALSE,
    moderation                      BOOLEAN      NOT NULL DEFAULT FALSE,
    reports                         BOOLEAN      NOT NULL DEFAULT FALSE,
    shadow_compare                  BOOLEAN      NOT NULL DEFAULT FALSE,
    legacy_delta_sync               BOOLEAN      NOT NULL DEFAULT FALSE,
    mobile_surface                  VARCHAR(16)  NOT NULL DEFAULT 'OFF',
    web_surface                     VARCHAR(16)  NOT NULL DEFAULT 'OFF',
    production_baseline_accepted    BOOLEAN      NOT NULL DEFAULT FALSE,
    -- D1-D4: policies for facts only the production baseline can settle.
    -- Every default is the conservative choice: quarantine, never guess.
    platform_author_policy          VARCHAR(24)  NOT NULL DEFAULT 'QUARANTINE',
    unregistered_gym_policy         VARCHAR(24)  NOT NULL DEFAULT 'QUARANTINE',
    primary_member_login_policy     VARCHAR(24)  NOT NULL DEFAULT 'QUARANTINE',
    null_branch_policy              VARCHAR(24)  NOT NULL DEFAULT 'QUARANTINE',
    authority_changed_at            TIMESTAMP,
    updated_at                      TIMESTAMP    NOT NULL DEFAULT NOW(),
    updated_by                      VARCHAR(255) NOT NULL DEFAULT 'system',
    version                         INTEGER      NOT NULL DEFAULT 0,
    CONSTRAINT ck_crs_singleton CHECK (id = 1),
    CONSTRAINT ck_crs_authority CHECK (authority IN ('LEGACY', 'GLOBAL')),
    CONSTRAINT ck_crs_write_mode CHECK (write_mode IN ('OPEN', 'READ_ONLY')),
    CONSTRAINT ck_crs_mobile CHECK (mobile_surface IN ('OFF', 'ALLOWLIST', 'ALL')),
    CONSTRAINT ck_crs_web CHECK (web_surface IN ('OFF', 'ALLOWLIST', 'ALL')),
    CONSTRAINT ck_crs_platform_author CHECK (platform_author_policy IN ('QUARANTINE', 'EXCLUDE', 'MIGRATE_AS_PLATFORM')),
    CONSTRAINT ck_crs_unregistered_gym CHECK (unregistered_gym_policy IN ('QUARANTINE', 'ALLOW')),
    CONSTRAINT ck_crs_member_login CHECK (primary_member_login_policy IN ('QUARANTINE', 'TENANT')),
    CONSTRAINT ck_crs_null_branch CHECK (null_branch_policy IN ('QUARANTINE', 'GYM_LEVEL')),
    -- Global surfaces and writes are meaningless while the legacy store is authoritative.
    CONSTRAINT ck_crs_global_requires_authority CHECK (
        authority = 'GLOBAL'
     OR (NOT op_post AND NOT op_comment AND NOT op_like AND NOT op_report AND NOT global_reads
         AND NOT moderation AND NOT reports AND mobile_surface = 'OFF' AND web_surface = 'OFF')
    ),
    CONSTRAINT ck_crs_authority_gate CHECK (authority = 'LEGACY' OR production_baseline_accepted),
    CONSTRAINT ck_crs_shadow_only_legacy CHECK (authority = 'LEGACY' OR (NOT shadow_compare AND NOT legacy_delta_sync))
);

