-- ── Guards ──────────────────────────────────────────────────────────────────

-- Append-only audit tables: rows can be inserted, never changed or removed.
CREATE OR REPLACE FUNCTION community_reject_mutation() RETURNS trigger AS $$
BEGIN
    RAISE EXCEPTION '% is append-only', TG_TABLE_NAME;
END;
$$ LANGUAGE plpgsql;

DROP TRIGGER IF EXISTS trg_cma_append_only ON community_moderation_actions;
CREATE TRIGGER trg_cma_append_only BEFORE UPDATE OR DELETE ON community_moderation_actions
    FOR EACH ROW EXECUTE FUNCTION community_reject_mutation();
DROP TRIGGER IF EXISTS trg_cma_no_truncate ON community_moderation_actions;
CREATE TRIGGER trg_cma_no_truncate BEFORE TRUNCATE ON community_moderation_actions
    FOR EACH STATEMENT EXECUTE FUNCTION community_reject_mutation();

DROP TRIGGER IF EXISTS trg_cra_append_only ON community_rollout_audit;
CREATE TRIGGER trg_cra_append_only BEFORE UPDATE OR DELETE ON community_rollout_audit
    FOR EACH ROW EXECUTE FUNCTION community_reject_mutation();
DROP TRIGGER IF EXISTS trg_cra_no_truncate ON community_rollout_audit;
CREATE TRIGGER trg_cra_no_truncate BEFORE TRUNCATE ON community_rollout_audit
    FOR EACH STATEMENT EXECUTE FUNCTION community_reject_mutation();

-- Authority is one-way: once GLOBAL, the legacy tables can no longer represent
-- every Community identity, so reverting would lose data.
CREATE OR REPLACE FUNCTION community_rollout_state_guard() RETURNS trigger AS $$
BEGIN
    IF TG_OP = 'DELETE' THEN
        RAISE EXCEPTION 'community_rollout_state cannot be deleted';
    END IF;
    IF OLD.authority = 'GLOBAL' AND NEW.authority <> 'GLOBAL' THEN
        RAISE EXCEPTION 'community authority cannot move from GLOBAL back to %', NEW.authority;
    END IF;
    IF OLD.production_baseline_accepted AND NOT NEW.production_baseline_accepted AND NEW.authority = 'GLOBAL' THEN
        RAISE EXCEPTION 'production baseline acceptance cannot be withdrawn after cutover';
    END IF;
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

DROP TRIGGER IF EXISTS trg_crs_guard ON community_rollout_state;
CREATE TRIGGER trg_crs_guard BEFORE UPDATE OR DELETE ON community_rollout_state
    FOR EACH ROW EXECUTE FUNCTION community_rollout_state_guard();
DROP TRIGGER IF EXISTS trg_crs_no_truncate ON community_rollout_state;
CREATE TRIGGER trg_crs_no_truncate BEFORE TRUNCATE ON community_rollout_state
    FOR EACH STATEMENT EXECUTE FUNCTION community_reject_mutation();
