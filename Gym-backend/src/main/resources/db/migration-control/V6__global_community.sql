    CONSTRAINT ck_gcc_origin CHECK (origin IN ('LEGACY', 'GLOBAL')),
    CONSTRAINT ck_gcc_slug CHECK (author_tenant_slug <> '' AND author_tenant_slug !~ '\s'),
